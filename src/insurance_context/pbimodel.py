"""A Power BI semantic model as plain data: read it from a .pbix or a TMDL folder, write it as TMDL.

    read_pbix(path)            tables, columns, measures, relationships, Power Query sources and RLS roles
    write_tmdl(model, folder)  a PBIP-style <name>.SemanticModel/definition folder
    read_tmdl(folder)          the same model back from TMDL (ours or one Power BI Desktop saved)

A .pbix keeps its model as a compressed binary; pbixray decodes it (pip install
insurance-context[powerbi]). TMDL is the reviewable, diffable form of the same model, so the
pipeline goes .pbix -> TMDL once and every later step reads TMDL. Power BI's own date tables
(LocalDateTable_*, DateTableTemplate_*) are generated by Desktop and are left out.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

_AUTO_TABLE = re.compile(r"^(LocalDateTable|DateTableTemplate)_[0-9a-f-]{36}$")
_DATA_TYPES = {"int64": "int64", "float64": "double", "string": "string", "object": "string", "bool": "boolean",
               "boolean": "boolean", "decimal": "decimal"}


@dataclass
class Column:
    name: str
    data_type: str = "string"
    source_column: str | None = None
    expression: str | None = None  # a calculated column (DAX); it exists only inside Power BI


@dataclass
class Measure:
    name: str
    expression: str
    format_string: str | None = None
    description: str | None = None


@dataclass
class Table:
    name: str
    columns: list[Column] = field(default_factory=list)
    measures: list[Measure] = field(default_factory=list)
    source: str | None = None       # Power Query (M), or DAX for a calculated table
    source_kind: str | None = None  # "m" | "calculated"

    def column(self, name: str) -> Column | None:
        return next((c for c in self.columns if c.name == name), None)


@dataclass
class Relationship:
    from_table: str
    from_column: str
    to_table: str
    to_column: str
    active: bool = True
    from_many: bool = True
    to_many: bool = False
    both_directions: bool = False


@dataclass
class Role:
    """A row-level security role: per table, a DAX filter a row must pass (definition/roles/<name>.tmdl)."""
    name: str
    model_permission: str = "read"
    tables: dict[str, str] = field(default_factory=dict)  # table -> DAX filter expression
    members: list[str] = field(default_factory=list)      # as stored in the model; access.yaml governs who is in it


@dataclass
class Model:
    name: str
    tables: dict[str, Table] = field(default_factory=dict)
    relationships: list[Relationship] = field(default_factory=list)
    roles: list[Role] = field(default_factory=list)

    def role(self, name: str) -> Role | None:
        return next((r for r in self.roles if r.name == name), None)

    @property
    def measures(self) -> list[tuple[str, Measure]]:
        return [(t.name, m) for t in self.tables.values() for m in t.measures]


# ------------------------------------------------------------------ .pbix

_OPEN: dict = {}


def _pbixray(path: str | Path):
    """One decoded .pbix, kept for the next call: decoding is the slow part (the whole model, every
    time), and an import reads the model and then each table's rows. pbixray also sizes every column
    by scanning its file list once per file, which is quadratic on a large model; we look them up."""
    from pbixray import PBIXRay
    try:
        from pbixray.meta.metadata import Metadata
    except ImportError:  # another pbixray layout: it works, only slower
        Metadata = None
    if Metadata is not None and not getattr(Metadata, "_indexed", False) and hasattr(Metadata, "_get_file_size_from_log"):
        def size(self, file_name):
            if not hasattr(self, "_sizes"):
                self._sizes = {x["FileName"]: x["SizeFromLog"] for x in self._data_model.file_log}
            return self._sizes.get(file_name, 0)
        Metadata._get_file_size_from_log, Metadata._indexed = size, True
    key = str(Path(path).resolve())
    if key not in _OPEN:
        _OPEN.clear()  # one file at a time: a decoded model is large
        _OPEN[key] = PBIXRay(key)
    return _OPEN[key]


def read_pbix(path: str | Path) -> Model:
    try:
        import pbixray  # noqa: F401
    except ImportError:
        raise ValueError(f"{path}: reading a .pbix needs pbixray (pip install insurance-context[powerbi]). "
                         "Or save it from Power BI Desktop as a PBIP project with TMDL turned on.") from None
    path = Path(path)
    try:
        px = _pbixray(path)
        names = list(px.tables)
    except Exception as e:  # live-connected reports have no model; pbixray raises its own error
        raise ValueError(f"{path}: could not read a model from this file ({type(e).__name__}: {e}). "
                         "A report connected live to a published model has none; read that model instead.") from None
    model = Model(path.stem)
    for n in names:
        if not _AUTO_TABLE.match(n):
            model.tables[n] = Table(n)
    calculated = {(r["TableName"], r["ColumnName"]): r["Expression"] for r in _records(px.dax_columns)}
    for r in _records(px.schema):
        t = model.tables.get(r["TableName"])
        if t is None:
            continue
        expr = calculated.get((t.name, r["ColumnName"]))
        t.columns.append(Column(r["ColumnName"], _data_type(r["PandasDataType"]),
                                None if expr is not None else r["ColumnName"], expr))
    for r in _records(px.dax_measures):
        t = model.tables.setdefault(r["TableName"], Table(r["TableName"]))
        t.measures.append(Measure(r["Name"], (r["Expression"] or "").strip(), None, r.get("Description") or None))
    for r in _records(px.power_query):
        if r["TableName"] in model.tables:
            model.tables[r["TableName"]].source, model.tables[r["TableName"]].source_kind = r["Expression"], "m"
    for r in _records(px.dax_tables):
        if r["TableName"] in model.tables:
            model.tables[r["TableName"]].source = r["Expression"]
            model.tables[r["TableName"]].source_kind = "calculated"
    for r in _records(px.relationships):
        if r["FromTableName"] not in model.tables or r["ToTableName"] not in model.tables:
            continue
        card = str(r.get("Cardinality") or "M:1")
        model.relationships.append(Relationship(
            r["FromTableName"], r["FromColumnName"], r["ToTableName"], r["ToColumnName"],
            active=bool(r.get("IsActive", 1)), from_many=card.startswith("M"), to_many=card.endswith("M"),
            both_directions=str(r.get("CrossFilteringBehavior")) == "Both"))
    roles: dict[str, Role] = {}
    for r in _records(px.rls):
        role = roles.setdefault(r["RoleName"], Role(r["RoleName"]))
        if r.get("FilterExpression") and r.get("TableName"):  # no filter: object-level security only
            role.tables[r["TableName"]] = str(r["FilterExpression"]).strip()
    for r in _records(px.tmschema_role_memberships):
        if r.get("MemberName"):
            roles.setdefault(r["RoleName"], Role(r["RoleName"])).members.append(str(r["MemberName"]))
    model.roles = list(roles.values())
    return model


def read_pbix_data(path: str | Path, table: str):
    """One imported table's rows (a pandas DataFrame), for a local stand-in of the warehouse."""
    return _pbixray(path).get_table(table)


def _records(frame) -> list[dict]:
    if frame is None or not hasattr(frame, "to_dict"):
        return []
    return [{k: (None if _isna(v) else v) for k, v in r.items()} for r in frame.to_dict("records")]


def _isna(v) -> bool:
    try:
        return v != v  # NaN
    except (TypeError, ValueError):
        return False


def _data_type(pandas_type) -> str:
    t = str(pandas_type).lower()
    if t.startswith("datetime"):
        return "dateTime"
    return _DATA_TYPES.get(t, "string")


# ------------------------------------------------------------------ TMDL out

def quote(name: str) -> str:
    """A TMDL name: bare when it is a plain identifier, else single-quoted with '' escaping."""
    return name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else "'" + name.replace("'", "''") + "'"


def _expr_lines(head: str, expr: str, depth: int) -> list[str]:
    """`head = expr` on one line, or the expression indented under it when it spans lines."""
    expr = expr.strip()
    if "\n" not in expr:
        return [f"{head} = {expr}"]
    lines = expr.splitlines()
    cut = min((len(x) - len(x.lstrip()) for x in lines[1:] if x.strip()), default=0)
    body = [lines[0].strip()] + [x[cut:] for x in lines[1:]]
    return [f"{head} ="] + [("\t" * depth + x) if x.strip() else "" for x in body]


def write_tmdl(model: Model, folder: str | Path) -> Path:
    """Write the model as <folder>/<name>.SemanticModel/definition and return that path."""
    root = Path(folder) / f"{model.name}.SemanticModel" / "definition"
    (root / "tables").mkdir(parents=True, exist_ok=True)
    (root / "database.tmdl").write_text("database\n\tcompatibilityLevel: 1567\n", encoding="utf-8")
    head = ["model Model", "\tculture: en-US", "\tdefaultPowerBIDataSourceVersion: powerBI_V3", ""]
    (root / "model.tmdl").write_text("\n".join(head + [f"ref table {quote(t)}" for t in model.tables]
                                               + [f"ref role {quote(r.name)}" for r in model.roles]) + "\n", encoding="utf-8")
    for t in model.tables.values():
        out = [f"table {quote(t.name)}", ""]
        for m in t.measures:
            lines = _expr_lines(f"\tmeasure {quote(m.name)}", m.expression, 3)
            out += lines
            if m.format_string:
                out.append(f"\t\tformatString: {m.format_string}")
            if m.description:
                out.append(f"\t\tdescription: {' '.join(m.description.split())}")
            out.append("")
        for c in t.columns:
            out += _expr_lines(f"\tcolumn {quote(c.name)}", c.expression, 3) if c.expression else \
                [f"\tcolumn {quote(c.name)}"]
            out.append(f"\t\tdataType: {c.data_type}")
            if c.source_column and not c.expression:
                out.append(f"\t\tsourceColumn: {c.source_column}")
            out.append("")
        if t.source:
            out.append(f"\tpartition {quote(t.name)} = {'calculated' if t.source_kind == 'calculated' else 'm'}")
            out.append(f"\t\tmode: import")
            out += ["\t\t" + x if i == 0 else x for i, x in enumerate(_expr_lines("source", t.source, 3))]
            out.append("")
        (root / "tables" / f"{_file_name(t.name)}.tmdl").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    rels = []
    for i, r in enumerate(model.relationships):
        rels += [f"relationship r{i + 1}",
                 f"\tfromColumn: {quote(r.from_table)}.{quote(r.from_column)}",
                 f"\ttoColumn: {quote(r.to_table)}.{quote(r.to_column)}"]
        if not r.from_many:
            rels.append("\tfromCardinality: one")
        if r.to_many:
            rels.append("\ttoCardinality: many")
        if r.both_directions:
            rels.append("\tcrossFilteringBehavior: bothDirections")
        if not r.active:
            rels.append("\tisActive: false")
        rels.append("")
    if rels:
        (root / "relationships.tmdl").write_text("\n".join(rels).rstrip() + "\n", encoding="utf-8")
    for r in model.roles:
        out = [f"role {quote(r.name)}", f"\tmodelPermission: {r.model_permission}", ""]
        out += [f"\tmember {quote(m)}" for m in r.members] + ([""] if r.members else [])
        for t, dax in r.tables.items():
            out += _expr_lines(f"\ttablePermission {quote(t)}", dax, 3) + [""]
        (root / "roles").mkdir(exist_ok=True)
        (root / "roles" / f"{_file_name(r.name)}.tmdl").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    return root


def _file_name(name: str) -> str:
    return re.sub(r'[<>:"/\\|?*]', "_", name)


# ------------------------------------------------------------------ TMDL in

_NAME = r"'(?:[^']|'')+'|[^\s='.]+"
_DECL = re.compile(rf"^(table|column|measure|partition|relationship|hierarchy|level|calculationItem|role|"
                   rf"tablePermission|columnPermission)\s+({_NAME})(?:\s*=\s*(.*))?$")
_MEMBER = re.compile(r"^member\s+('(?:[^']|'')+'|\S+)")
_PROP = re.compile(r"^([A-Za-z]+)\s*(:|=)\s*(.*)$")


def _unquote(name: str) -> str:
    name = name.strip()
    return name[1:-1].replace("''", "'") if name.startswith("'") and name.endswith("'") else name


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip())


def expression(lines: list[str], i: int, first: str) -> tuple[str, int]:
    """The expression after `x =`, and the index of the line after it.

    TMDL writes a short expression on the same line. A long one starts on the next line, indented
    deeper than the object's properties (formatString, lineageTag), or sits between ``` fences."""
    if first and first != "```":
        return first, i
    body = []
    if first == "```":
        while i < len(lines) and lines[i].strip() != "```":
            body.append(lines[i])
            i += 1
        i += 1
    else:
        depth = None
        while i < len(lines):
            line = lines[i]
            if line.strip():
                if depth is None:
                    depth = _indent(line)
                elif _indent(line) < depth:
                    break
            elif depth is None:
                i += 1
                continue
            body.append(line)
            i += 1
    while body and not body[-1].strip():
        body.pop()
    cut = min((_indent(b) for b in body if b.strip()), default=0)
    return "\n".join(b[cut:].rstrip() for b in body), i


def _column_ref(text: str) -> tuple[str, str]:
    m = re.fullmatch(rf"\s*({_NAME})\.({_NAME})\s*", text)
    if not m:
        raise ValueError(f"cannot read column reference {text!r}")
    return _unquote(m.group(1)), _unquote(m.group(2))


def read_tmdl(folder: str | Path) -> Model:
    """A model from TMDL: every *.tmdl under `folder` (a PBIP project, its .SemanticModel, or definition)."""
    folder = Path(folder)
    sm = next(iter(sorted(folder.rglob("*.SemanticModel"))), None)
    model = Model(sm.name.removesuffix(".SemanticModel") if sm else folder.name)
    for f in sorted(folder.rglob("*.tmdl")):
        _read_file(f, model)
    return model


def _read_file(f: Path, model: Model) -> None:
    lines = f.read_text(encoding="utf-8-sig").splitlines()
    table: Table | None = None
    role: Role | None = None
    obj = None  # the Column / Measure / Relationship / partition dict whose properties follow
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        text = line.strip()
        if not text or text.startswith("///"):
            continue
        member = _MEMBER.match(text)
        if member and role is not None:
            role.members.append(_unquote(member.group(1)))
            obj = None
            continue
        m = _DECL.match(text)
        if m:
            kind, name, rest = m.group(1), _unquote(m.group(2)), (m.group(3) or "").strip()
            if kind == "table":
                table, role = model.tables.setdefault(name, Table(name)), None
                obj = table
            elif kind == "role":
                role, table = model.role(name), None
                if role is None:
                    role = Role(name)
                    model.roles.append(role)
                obj = role
            elif kind == "tablePermission" and role is not None:
                obj = None
                if m.group(3) is not None:
                    role.tables[name], i = expression(lines, i, rest)
            elif kind == "measure" and table is not None:
                expr, i = expression(lines, i, rest)
                obj = Measure(name, expr)
                table.measures.append(obj)
            elif kind == "column" and table is not None:
                expr = None
                if rest:
                    expr, i = expression(lines, i, rest)
                obj = Column(name, "string", None, expr)
                table.columns.append(obj)
            elif kind == "partition" and table is not None:
                table.source_kind = "calculated" if rest == "calculated" else "m"
                obj = ("partition", table)
            elif kind == "relationship":
                obj = Relationship("", "", "", "")
                model.relationships.append(obj)
            else:
                obj = None
            continue
        p = _PROP.match(text)
        if not p or obj is None:
            continue
        key, sep, value = p.group(1), p.group(2), p.group(3).strip()
        if sep == "=":
            if key == "source" and isinstance(obj, tuple):
                obj[1].source, i = expression(lines, i, value)
            continue
        if isinstance(obj, Role):
            if key == "modelPermission":
                obj.model_permission = value
        elif isinstance(obj, Measure):
            if key == "formatString":
                obj.format_string = value
            elif key == "description":
                obj.description = value
        elif isinstance(obj, Column):
            if key == "dataType":
                obj.data_type = value
            elif key == "sourceColumn":
                obj.source_column = value
        elif isinstance(obj, Relationship):
            if key == "fromColumn":
                obj.from_table, obj.from_column = _column_ref(value)
            elif key == "toColumn":
                obj.to_table, obj.to_column = _column_ref(value)
            elif key == "fromCardinality":
                obj.from_many = value == "many"
            elif key == "toCardinality":
                obj.to_many = value == "many"
            elif key == "crossFilteringBehavior":
                obj.both_directions = value == "bothDirections"
            elif key == "isActive":
                obj.active = value != "false"
